-- activacionPorTelefono, Epic 2 Task 2.1: hace obligatoria pacientes.fecha_nacimiento,
-- el segundo factor del canje del OTP en la app móvil — una ficha sin fecha
-- nunca puede activarse.
--
-- Hand-written (db diff no funciona en este repo — shadow DB rota, ver
-- supabase/migrations/20260830170100_baja_voluntaria_foundational.sql).
-- Mirrors el estado final de supabase/schemas/21_pacientes.sql y
-- supabase/schemas/71_rpcs_pacientes.sql. Se apoya en las versiones de
-- register_paciente y update_paciente_identidad que dejó la Task 0.1 de
-- epic-0-fundacion-transversal.md (guard telefono_requerido), timestamp
-- posterior a supabase/migrations/20260915123000_solicitar_otp_activacion.sql.
--
-- Orden:
--   1. Guard: aborta si hay fichas con fecha_nacimiento null (solo se listan ids).
--   2. alter column fecha_nacimiento set not null.
--   3. create or replace de register_paciente y update_paciente_identidad con
--      el guard fecha_nacimiento_requerida nuevo + comments actualizados.

-- ---------------------------------------------------------------------------
-- 1. Guard: abortar si alguna ficha no tiene fecha_nacimiento.
--    Solo se listan ids (nunca datos personales).
-- ---------------------------------------------------------------------------

do $$
declare
  v_ids uuid[];
begin
  select array_agg(p.id)
    into v_ids
    from public.pacientes as p
   where p.fecha_nacimiento is null;

  if v_ids is not null then
    raise exception 'fecha_nacimiento_obligatoria: % ficha(s) sin fecha de nacimiento, ids: %',
      array_length(v_ids, 1), v_ids;
  end if;
end;
$$;

